'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {app} = require('electron');
const cnode = require('../../electron/cnode.cjs');
app.disableHardwareAcceleration();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'codenode-canvas-navigation-'));
process.env.CODENODE_USER_DATA_DIR = path.join(temp, 'userdata');
process.env.CODENODE_HOME = path.join(temp, 'home');
const roots = ['alpha', 'beta'].map(name => path.join(temp, name));
roots.forEach((root, index) => {
  fs.mkdirSync(root);
  fs.writeFileSync(path.join(root, 'workflow.cnode'), cnode.encodeCnode({graph:{nodes:[],edges:[]},canvases:{sessions:[{id:`chat-${index}`,label:`项目聊天 ${index}`,status:'active',createdAt:Date.now(),nodeCount:0,messages:[{role:'user',content:`项目 ${index} 的内容`}],root:{nodes:[],edges:[]}}],messages:[]}}));
});
let win;
const errors = [];
app.on('browser-window-created', (_event, window) => { win = window; win.hide(); window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); }); });
require('../../electron/main.cjs');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const js = code => win.webContents.executeJavaScript(code).catch(error => { console.error('Renderer command failed:', code, errors); throw error; });
async function until(code, label) { for (let i = 0; i < 160; i++) { if (await js(code)) return; await sleep(60); } throw Error('等待超时: '+label); }
app.whenReady().then(async () => { try {
  while (!win) await sleep(60);
  await until('!!window.__codenodeUi?.getState().booted && !!window.__codenodeSession', '工作台启动');
  assert.ok(win.webContents.getURL().includes('index.html'));
  await js(`localStorage.setItem('codenode.recentProjects', ${JSON.stringify(JSON.stringify(roots.map(root => ({root,file:path.join(root,'workflow.cnode'),name:path.basename(root),openedAt:Date.now()}))))});window.__codenodeUi.getState().updatePreferences({workbenchView:'canvas',autoSaveEnabled:false});window.__codenodeUi.setState({navigationOpen:true,conversationOpen:true});`);
  await until("document.querySelectorAll('.project-group-name').length===2", '项目文件夹');
  assert.equal(await js('window.__codenodeProject.getState().root'), null);
  await js("[...document.querySelectorAll('.project-group-name')].find(b=>b.textContent.includes('beta')).click()");
  await until("document.querySelector('.project-nav-sessions')?.innerText.includes('项目聊天 1')", '跨项目聊天预览');
  assert.equal(await js('window.__codenodeProject.getState().root'), null, '展开项目不切换工作区');
  await js("[...document.querySelectorAll('.project-nav-sessions button')].find(b=>b.textContent==='项目聊天 1').click()");
  await until("window.__codenodeSession.getState().activeId==='chat-1'", '切换到对应项目聊天');
  assert.equal(await js('window.__codenodeProject.getState().root'), roots[1]);
  await js("document.querySelector('[aria-label=\"切换到画布\"]').click()");
  await until("document.querySelector('.canvas-actions')?.getBoundingClientRect().width>0", '画布工具可见');
  const rects = await js(`(() => {const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}};return {canvas:rect('.canvas-wrap'),actions:rect('.canvas-actions'),conversation:rect('.conversation-right')}})()`);
  assert.ok(rects.actions.x >= rects.canvas.x && rects.actions.x < rects.canvas.x + 30);
  assert.ok(rects.actions.y >= rects.canvas.y && rects.actions.y < rects.canvas.y + 30);
  assert.ok(rects.conversation.x >= rects.canvas.x + rects.canvas.width - 2);
  assert.equal(await js("!!document.querySelector('.toolbar .toolbar-dropdown')"), false);
  assert.equal(await js("!!document.querySelector('.activity-bar')"), false, '展开工作台侧栏时不再叠加图标栏');
  await js("document.querySelector('.toolbar-navigation-toggle').click()");
  await until("!document.querySelector('.project-navigation') && !!document.querySelector('.activity-bar')", '收起侧栏');
  await js("document.querySelector('.toolbar-navigation-toggle').click()");
  await until("!!document.querySelector('.project-navigation') && !document.querySelector('.activity-bar')", '恢复单侧栏');
  await js("document.querySelector('.sidebar-links [aria-label=\"文件\"]').click()");
  await until("!!document.querySelector('.workspace-project')", '侧栏文件入口');
  await js("document.querySelector('.sidebar-home').click()");
  await until("!!document.querySelector('.workspace-agent')", '返回工作台');
  for (const [label, selector] of [['插件','.plugin-workspace'],['任务','.task-workspace:not([hidden])']]) {
    await js(`document.querySelector('.sidebar-links [aria-label="${label}"]').click()`);
    await until(`!!document.querySelector('${selector}') && !!document.querySelector('.activity-bar')`, label + '入口');
    await js("document.querySelector('.activity-bar [aria-label=\"工作台\"]').click()");
    await until("!!document.querySelector('.project-navigation') && !document.querySelector('.activity-bar')", '返回项目侧栏');
  }
  await js("document.querySelector('.sidebar-footer .global-settings-trigger').click()");
  await until("!!document.querySelector('.settings-close')", '侧栏设置入口');
  await js("document.querySelector('.settings-close').click()");
  await until("!document.querySelector('.global-settings')", '关闭设置');


  await js("document.querySelector('.canvas-actions summary').click()");
  await until("document.querySelector('.canvas-actions').open", '展开画布菜单');
  await js("document.querySelector('.canvas-actions').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await js("document.querySelector('.canvas-actions').open"), false);
  const zoom = await js('window.__codenodeUi.getState().viewport.zoom');
  await js("document.querySelector('[aria-label=\"放大画布\"]').click()");
  await until(`window.__codenodeUi.getState().viewport.zoom > ${zoom}`, '缩放生效');
  await js("document.querySelector('[aria-label=\"拖动画布\"]').click()");
  assert.equal(await js("document.querySelector('[aria-label=\"拖动画布\"]').getAttribute('aria-pressed')"), 'true');
  await js("document.querySelector('[aria-label=\"选择工具\"]').click()");
  assert.equal(await js("document.querySelector('[aria-label=\"选择工具\"]').getAttribute('aria-pressed')"), 'true');
  assert.equal(await js("document.querySelector('.branch-panel-trigger').textContent"), '代码方案');
  assert.equal(await js("!!document.querySelector('.crash,.vite-error-overlay')"), false);
  await js("document.querySelector('[aria-label=\"关闭入门引导\"]')?.click();window.__codenodeStore.getState().loadDocument({nodes:[{id:'input',type:'task',position:{x:80,y:120},data:{label:'整理需求',prompt:'收集需求与项目文件',status:'done'}},{id:'implement',type:'task',position:{x:360,y:280},data:{label:'实现功能',prompt:'编写并验证代码',status:'pending'}}],edges:[{id:'step',source:'input',target:'implement'}]});");
  await sleep(200);
  await js("document.querySelector('[aria-label=\"适应画布\"]').click()");
  await sleep(400);
  assert.equal(await js("document.querySelector('.canvas-zoom-controls span').textContent"), await js("[...document.querySelectorAll('.status-bar span')].find(e=>e.textContent.startsWith('缩放 ')).textContent.replace('缩放 ','')"));
  win.setSize(1440, 960); win.showInactive(); await sleep(150);
  const skin = await js(`(() => {const style=getComputedStyle(document.querySelector('.app'));return {canvas:style.getPropertyValue('--glass-base').trim(),accent:style.getPropertyValue('--glass-accent').trim(),navigation:getComputedStyle(document.querySelector('.project-navigation')).backgroundColor,brand:getComputedStyle(document.querySelector('.project-nav-head .xiaohuang-avatar')).display,mascot:document.querySelector('.xiaohuang-illustration').getBoundingClientRect().height,ornaments:getComputedStyle(document.querySelector('.canvas-ornaments')).display}})()`);
  assert.equal(skin.canvas, '#fffcf5');
  assert.equal(skin.accent, '#48693b');
  assert.equal(skin.navigation, 'rgb(246, 232, 201)');
  assert.notEqual(skin.brand, 'none');
  assert.equal(skin.mascot, 48);
  assert.notEqual(skin.ornaments, 'none');
  assert.equal(await js("getComputedStyle(document.querySelector('.branch-panel-trigger')).fontSize"), '12px');

  fs.writeFileSync(path.join(os.tmpdir(), 'codenode-canvas-navigation-desktop.png'), (await win.webContents.capturePage()).toPNG());
  assert.equal(await js("!!document.querySelector('.toolbar-vector')"), false);
  await js("document.querySelector('[aria-label=\"添加节点\"]').click()");
  await until("!!document.querySelector('#canvas-add-menu')", '底部添加菜单');
  const addLayout = await js(`(() => {const menu=document.querySelector('#canvas-add-menu').getBoundingClientRect(),button=document.querySelector('[aria-label="添加节点"]').getBoundingClientRect();return {bottom:menu.bottom,top:menu.top,right:menu.right,button:button.top,width:innerWidth}})()`);
  assert.ok(addLayout.bottom <= addLayout.button && addLayout.top >= 8 && addLayout.right <= addLayout.width - 8, '菜单向上展开并保持在窗口内');
  await sleep(200);
  fs.writeFileSync(path.join(os.tmpdir(), 'codenode-bottom-add-menu.png'), (await win.webContents.capturePage()).toPNG());
  const beforeAdd = await js('window.__codenodeStore.getState().nodes.length');
  await js("[...document.querySelectorAll('.add-menu-item')].find(e=>e.querySelector('.add-menu-label').textContent==='新建任务').click()");
  await until(`window.__codenodeStore.getState().nodes.length===${beforeAdd+1}`, '底部添加任务节点');
  assert.equal(await js("!!document.querySelector('#canvas-add-menu')"), false);
  await js("window.__codenodeStore.getState().undo();window.__codenodeUi.getState().updatePreferences({advancedMode:false})");

  win.setSize(900, 720); await sleep(150);
  fs.writeFileSync(path.join(os.tmpdir(), 'codenode-canvas-navigation-compact.png'), (await win.webContents.capturePage()).toPNG());
  const trigger = await js("(()=>{const e=document.querySelector('.branch-panel-trigger');return {scroll:e.scrollWidth,width:e.clientWidth}})()");
  assert.ok(trigger.scroll <= trigger.width + 1, '方案入口文字不截断');
  assert.deepEqual(errors, []);
  console.log('CANVAS NAVIGATION UI: PASS (project previews, workspace switch, canvas controls, menu dismissal, layout, console)');
  app.exit(0);
} catch (error) { console.error(error); app.exit(1); } });
