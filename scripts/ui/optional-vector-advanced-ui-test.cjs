'use strict';
// Browser plugin not available: use the repository's native Electron UI harness.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {app, BrowserWindow} = require('electron');
app.disableHardwareAcceleration();
const project = fs.mkdtempSync(path.join(os.tmpdir(), 'codenode-optional-vector-'));
const source = path.join(__dirname, '../..');
process.env.CODENODE_USER_DATA_DIR = path.join(project, 'userData');
process.env.CODENODE_HOME = path.join(project, 'home');
process.env.CODENODE_SOUL_FILE = path.join(project, 'soul.md');
app.on('browser-window-created', (_event, win) => { win.show = () => {}; win.hide(); });
require(path.join(source, 'electron/main.cjs'));
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({show:false,width:1500,height:900,webPreferences:{sandbox:true,backgroundThrottling:false,preload:path.join(source,'electron/preload.cjs')}});
  const errors = [];
  win.webContents.on('console-message', details => { if (details.level === 'error') errors.push(details.message); });
  const js = async code => { try { return await win.webContents.executeJavaScript(code); } catch(error) { throw new Error(String(error)+' / '+code+' / console: '+errors.join(' | ')); } };
  const wait = async (code, label) => { for (let i=0;i<150;i++) { if(await js(code))return;await sleep(50); } throw Error('Timeout: '+label); };
  try {
    await win.loadFile(path.join(source,'dist/index.html'));
    await wait('!!window.__codenodeProject', 'app');
    await js(`window.__codenodeProject.getState().loadRoot(${JSON.stringify(project)})`);
    await js(`window.__codenodeSession.getState().newCanvas();window.__codenodeUi.getState().updatePreferences({autoSaveEnabled:false});window.__codenodeUi.setState({sideTab:'agent',sideOpen:false,conversationOpen:false});window.__codenodeStore.getState().load([{id:'task',type:'task',position:{x:300,y:100},data:{label:'保留任务',prompt:'保留原始任务',status:'pending'}}],[])`);
    await wait('!!document.querySelector(".canvas-wrap")', 'canvas');await sleep(400);
    assert.deepEqual(await js(`(()=>{const p=window.__codenodeUi.getState().preferences;return[p.advancedMode,p.vectorEditorEnabled]})()`),[true,true]);
    await wait(`typeof window.__codenodeVectorNode === 'function'`,'default plugin loaded');
    await js(`window.__codenodeUi.getState().updatePreferences({vectorEditorEnabled:false})`);
    await wait(`!document.querySelector('.toolbar-vector')`,'drawing button hidden when disabled');
    // Simulate an existing project containing a vector node, with its original v2 storage key.
    await js(`window.__codenodeStore.getState().load([{id:'legacy',type:'vector',position:{x:100,y:100},data:{label:'旧绘图',width:1040,height:640,mode:'design'}}],[]);window.__codenodeStore.getState().setSelectedIds(['legacy']);`);
    await wait(`!!document.querySelector('[data-testid="vector-plugin-placeholder"]')`,'legacy placeholder');
    await js(`window.__codenodeUi.getState().openSettings('layout')`);
    await wait(`!!document.querySelector('[aria-label="矢量编辑器插件"]')`,'plugin management');
    await js(`document.querySelector('[aria-label="启用矢量编辑器"]').click()`);
    await wait(`typeof window.__codenodeVectorNode==='function'`,'plugin loaded');
    await js(`window.__codenodeUi.getState().closeSettings()`);
    await wait(`!!document.querySelector('[data-testid="vector-node"] .vs-stage')`,'editor');
    await js(`(()=>{const s=window.__codenodeVectorNode('legacy').getState();s.addFromPreset('rectangle', {x:0,y:0});s.saveProject()})()`);
    const documentBefore = await js(`JSON.stringify(window.__codenodeVectorNode('legacy').getState().objects)`);
    const graphBefore = await js(`JSON.stringify(window.__codenodeStore.getState().nodes.map(({id,type,data,position})=>({id,type,data,position})))`);
    await js(`window.__codenodeUi.getState().openSettings('layout')`);
    await wait(`!!document.querySelector('[aria-label="停用矢量编辑器"]')`,'disable control');
    await js(`document.querySelector('[aria-label="停用矢量编辑器"]').click();window.__codenodeUi.getState().closeSettings()`);
    await wait(`!document.querySelector('[data-testid="vector-node"]') && !!document.querySelector('[data-testid="vector-plugin-placeholder"]')`,'plugin disabled');
    assert.equal(await js(`JSON.stringify(window.__codenodeStore.getState().nodes.map(({id,type,data,position})=>({id,type,data,position})))`),graphBefore);
    await js(`document.querySelector('.vector-plugin-placeholder button').click()`);
    await wait(`!!document.querySelector('[data-testid="vector-node"]')`,'reactivation');
    assert.equal(await js(`JSON.stringify(window.__codenodeVectorNode('legacy').getState().objects)`),documentBefore);
    await win.webContents.capturePage().then(image=>fs.writeFileSync(path.join(project,'plugin-enabled.png'),image.toPNG()));
    // Save while the plugin is disabled; reopening must preserve opaque vector nodes and drawings.
    await js(`window.__codenodeUi.getState().updatePreferences({vectorEditorEnabled:false})`);
    await js(`window.__codenodeProject.getState().setProjectFile(${JSON.stringify(path.join(project,'legacy.cnode'))})`);
    await wait(`!!document.querySelector('.project-row-menu [data-action="save"]')`,'project save action');
    await js(`document.querySelector('.project-row-menu [data-action="save"]').click()`);
    await wait(`localStorage.getItem('codenode.lastProjectFile')===${JSON.stringify(path.join(project,'legacy.cnode'))}`,'project saved');
    win.webContents.reload();await wait(`!!document.querySelector('.workspace-home')`,'reload workspace home');
    await wait(`!!document.querySelector('.project-group-name')`,'saved recent project');
    await js(`document.querySelector('.project-group-name').click()`);
    await wait(`!!document.querySelector('.workbench-view-switch')`,'reload workbench');
    assert.deepEqual(await js(`(()=>{const p=window.__codenodeUi.getState().preferences;return[p.advancedMode,p.vectorEditorEnabled]})()`),[true,false]);
    assert.equal(await js(`typeof window.__codenodeVectorNode`),'undefined');
    await wait(`window.__codenodeStore.getState().nodes.some(n=>n.id==='legacy' && n.type==='vector')`,'saved .cnode vector restored');
    assert.equal(await js(`window.__codenodeStore.getState().nodes.some(n=>n.id==='legacy' && n.type==='vector')`),true,'saved .cnode retains vector node while plugin is off');
    await js(`window.__codenodeUi.getState().updatePreferences({vectorEditorEnabled:true})`);
    await wait(`typeof window.__codenodeVectorNode==='function' && window.__codenodeVectorNode('legacy').getState().ready`,'storage restored');
    assert.equal(await js(`JSON.stringify(window.__codenodeVectorNode('legacy').getState().objects)`),documentBefore);
    await js(`window.__codenodeUi.getState().openSettings('layout')`);await wait(`!!document.querySelector('[aria-label="矢量编辑器插件"]')`,'plugins screenshot');
    await js(`document.querySelector('.vector-plugin-card').closest('details').open=true`);
    await sleep(250);
    assert.equal(await js(`(()=>{const r=document.querySelector('[aria-label="矢量编辑器插件"]').getBoundingClientRect();return r.width>280 && r.right<=innerWidth})()`),true,'desktop plugin card must fit');
    fs.writeFileSync(path.join(project,'plugins-desktop.png'),(await win.webContents.capturePage()).toPNG());
    win.setSize(900,700);await sleep(250);
    assert.equal(await js(`(()=>{const r=document.querySelector('[aria-label="矢量编辑器插件"]').getBoundingClientRect();return r.width>280 && r.right<=innerWidth})()`),true,'narrow plugin card must fit');
    fs.writeFileSync(path.join(project,'plugins-narrow.png'),(await win.webContents.capturePage()).toPNG());
    assert.deepEqual(errors,[],'renderer console errors');
    console.log('OPTIONAL VECTOR / ADVANCED UI: PASS (reference defaults, enable/disable, old data, cold reload, desktop/narrow, console)');
    console.log('Screenshots: '+project);
  } finally {win.destroy();app.quit();}
}).catch(error=>{console.error(error);app.exit(1);});
